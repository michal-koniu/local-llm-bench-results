def load():
    cfg = yaml.safe_load(CONFIG.read_text())
    return cfg, cfg.get("models", {})


def engine_of(mid, m):
    cmd = m["cmd"]
    env = " ".join(m.get("env") or [])
    files = [f"`{CONFIG}` (entry `{mid}`)"]
    gpus = re.search(r"\bGPUS=(\S+)", cmd) or re.search(r"(?:GGML_VK_VISIBLE_DEVICES|HIP_VISIBLE_DEVICES|CUDA_VISIBLE_DEVICES)=(\S+)", env)
    gpus = f"GPU {gpus.group(1)}" if gpus else "all 4 GPUs"
    compose = re.search(r"(\S+\.compose\.yml)", cmd)
    if "radiance/" in cmd:
        eng = "radiance engine (C++/HIP inference server for RDNA4 by StillDeadcode, Docker image stilldeadcode/radiance)"
        files += [f"`{compose.group(1)}` (container settings)", f"`{LS}/vllm/run-compose.sh` (start/stop wrapper)",
                  "`~/radiance-engine/` (engine source and docs/GUIDE.md)"]
        md = re.search(r"MODELDIR=(\S+)", cmd)
        files.append(f"`{md.group(1) if md else '/home/mkoniu/models/qwen3.8-flash-next/radiance'}` (model weights, .rad)")
    elif "vllm/" in cmd and compose:
        eng = "vLLM, Radiance fork for R9700 (Docker image stilldeadcode/vllm-radiance), behind a small nginx front"
        files += [f"`{compose.group(1)}` (vLLM flags and environment)", f"`{LS}/vllm/run-compose.sh` (start/stop wrapper)",
                  f"`{LS}/vllm/front.compose.yml` + `front.conf.template` (nginx front)",
                  "`~/radiance-vllm-mxfp4/` (fork scripts, chat templates)"]
    else:
        binary = cmd.split()[0]
        backend = "Vulkan" if "vulkan" in binary else "ROCm/HIP"
        eng = f"llama.cpp llama-server ({backend} build `{binary}`)"
        files.append(f"`{LS}/ui/{mid}.json` (chat UI defaults: this prompt, agentic turns)")
        model = re.search(r"(?:-m|--model)\s+(\S+)", cmd)
        if model:
            files.append(f"`{model.group(1)}` (model weights)")
    return eng, gpus, files


def prompt(mid, m, ui):
    eng, gpus, files = engine_of(mid, m)
    cmd = textwrap.dedent(m["cmd"]).strip()
    return f"""# You
You are **{m.get('name', mid)}** -- llama-swap model id `{mid}` -- a local model on the user's own AI server.
{m.get('description', '').strip()}
- Engine: {eng}; runs on {gpus}.
- Started by llama-swap with:
```
{cmd}
```
- Your configuration files:
{chr(10).join('  - ' + f for f in files)}

# Where you run
{MACHINE}
{SERVING}

# Tools
{TOOLS_WEBUI if ui == 'webui' else TOOLS_LLAMACPP}

{RULES}
{bootstrap(ui)}"""


def bootstrap(ui):
    # hand-written shared context (Tor proxy, ~/ai_skills, policy); edit that file, then rerun this script
    f = LS / "AGENT_BOOTSTRAP.md"
    if not f.is_file():
        return ""
    note = "(In this UI the shell tool is `run_command`, not `exec_shell_command`.)\n\n" if ui == "webui" else ""
    body = re.sub(r"(?m)^# ", "## ", f.read_text().strip())
    return f"\n# Local notes from `{f}`\n{note}{body}\n"


def write_files(models):
    (LS / "prompts").mkdir(exist_ok=True)
    (LS / "ui").mkdir(exist_ok=True)
    for mid, m in models.items():
        for ui in ("webui", "llamacpp"):
            (LS / "prompts" / f"{mid}.{ui}.md").write_text(prompt(mid, m, ui))
        if "llama-server" in m["cmd"]:
            (LS / "ui" / f"{mid}.json").write_text(json.dumps(
                {"agenticMaxTurns": 10000, "systemMessage": prompt(mid, m, "llamacpp")}, indent=1))
    print(f"wrote prompts for {len(models)} models to {LS}/prompts, llama.cpp UI defaults to {LS}/ui")


def webui_token():
    code = ("import jwt,time,sqlite3,os;k=os.environ.get('WEBUI_SECRET_KEY') or open('/app/backend/.webui_secret_key').read().strip();"
            "c=sqlite3.connect('/app/backend/data/webui.db');u=c.execute(\"select id from user where role='admin' "
            "order by created_at limit 1\").fetchone()[0];st=c.execute('select session_stamp from auth where id=?',(u,)).fetchone()[0];"
            "print(jwt.encode({'id':u,'session_stamp':st,'exp':int(time.time())+600},k,algorithm='HS256'))")
    r = subprocess.run(["docker", "exec", "open-webui", "python3", "-c", code], capture_output=True, text=True)
    if r.returncode:
        sys.exit("cannot get an Open WebUI admin token (is the open-webui container running?):\n" + r.stderr[-800:])
    return r.stdout.strip()


def api(token, method, path, body=None):
    req = urllib.request.Request(WEBUI + path, method=method, data=json.dumps(body).encode() if body is not None else None,
                                 headers={"Authorization": "Bearer " + token, "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read() or b"null")


def sync_webui(models):
    t = webui_token()
    key = (HOME / ".config" / "rig-tools" / "token").read_text().strip()
    conns = [c for c in api(t, "GET", "/api/v1/configs/tool_servers")["TOOL_SERVER_CONNECTIONS"]
             if (c.get("info") or {}).get("id") != "rig-tools"]
    conns.append({"url": MCP_URL, "path": "", "type": "mcp", "auth_type": "bearer", "key": key,
                  "config": {"enable": True},        # no access_grants = admin accounts only
                  "info": {"id": "rig-tools", "name": "rig-tools",
                           "description": "Shell, files and internet on the rig (~/.config/llama-swap/tools/rig_tools.py)"}})
    api(t, "POST", "/api/v1/configs/tool_servers", {"TOOL_SERVER_CONNECTIONS": conns})

    mc = api(t, "GET", "/api/v1/configs/models")
    mc["DEFAULT_MODEL_METADATA"] = {**(mc.get("DEFAULT_MODEL_METADATA") or {}), "toolIds": [TOOL_ID]}
    mc["DEFAULT_MODEL_PARAMS"] = {**(mc.get("DEFAULT_MODEL_PARAMS") or {}), "function_calling": "native"}
    api(t, "POST", "/api/v1/configs/models", mc)

    for mid, m in models.items():
        form = {"id": mid, "base_model_id": None, "name": m.get("name", mid),
                "meta": {"description": m.get("description", ""), "toolIds": [TOOL_ID]},
                "params": {"system": prompt(mid, m, "webui"), "function_calling": "native"}, "is_active": True}
        try:
            existing = api(t, "GET", "/api/v1/models/model?id=" + mid)
        except urllib.error.HTTPError:
            existing = None
        if existing:
            form["meta"] = {**(existing.get("meta") or {}), **form["meta"]}
            form["params"] = {**(existing.get("params") or {}), **form["params"]}
            api(t, "POST", "/api/v1/models/model/update", form)
        else:
            api(t, "POST", "/api/v1/models/create", form)
    print(f"Open WebUI: rig-tools connected, tools on by default, prompts set for {len(models)} models")


if __name__ == "__main__":
    cfg, models = load()
    write_files(models)
    if "--no-webui" not in sys.argv:
        sync_webui(models)
